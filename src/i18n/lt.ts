const st = (n: number, [vienas, keli, daug]: [string, string, string]) => {
  const d = n % 10;
  const s = n % 100;
  if (d === 1 && s !== 11) return vienas;
  if (d >= 2 && (s < 10 || s > 20)) return keli;
  return daug;
};

